"""Index the hero's high-resolution map source frames for the painted room.

    python tools/hero_source_frames.py

Reads assets/characters/hero/map/<direction>/sources/*.png (the newest attempt of each frame), measures the
solid figure box and the anchor (head centre, feet line) of each frame and writes game_factory/hero_map_source_frames.json.
No image is created or changed; the game scales the sources itself (scenes/hero_source_art.gd).

Execution provenance: Agent: claude (Claude Code); model: Fable 5.2.
"""
from __future__ import annotations

import json
import re
from pathlib import Path

import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "game_factory" / "hero_map_source_frames.json"
NAME = re.compile(r"hero_map_(down|left|right|up)_(idle|walk)_(\d+)(?:_v\d+)?__attempt_(\d+)\.png$")


def measure(path: Path) -> dict:
    alpha = np.array(Image.open(path).convert("RGBA"))[:, :, 3] > 128
    ys, xs = np.where(alpha)
    top, bottom = int(ys.min()), int(ys.max()) + 1
    head = alpha[top:top + (bottom - top) // 4]  # the top quarter: the head stays put while feet and sword move
    head_xs = np.where(head)[1]
    return {"path": "res://" + path.relative_to(ROOT).as_posix(), "box": [int(xs.min()), top, int(xs.max()) + 1, bottom],
            "anchor": [int(round((int(head_xs.min()) + int(head_xs.max())) / 2)), bottom]}


def build() -> dict:
    animations: dict[str, list] = {}
    for direction in ("down", "left", "right", "up"):
        newest: dict[tuple, tuple] = {}
        for path in sorted((ROOT / "assets/characters/hero/map" / direction / "sources").glob("*.png")):
            match = NAME.match(path.name)
            if match and (key := (match.group(2), int(match.group(3)))) and int(match.group(4)) >= newest.get(key, (0, None))[0]:
                newest[key] = (int(match.group(4)), path)
        for (state, _number), (_attempt, path) in sorted(newest.items()):
            animations.setdefault(f"map_{direction}_{state}", []).append(measure(path))
    # The directions were drawn at slightly different sizes: each animation records its own mean figure height.
    heights = {key: round(sum(f["box"][3] - f["box"][1] for f in frames) / len(frames)) for key, frames in animations.items()}
    return {"schema_version": 1, "note": "Generated by tools/hero_source_frames.py; sources are local files that Godot does not import.",
            "figure_heights": heights, "fps": {"idle": 3, "walk": 9}, "animations": animations}


if __name__ == "__main__":
    data = build()
    OUT.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8", newline="\n")
    print(f"HERO_SOURCE_FRAMES {sum(len(v) for v in data['animations'].values())} frames")
