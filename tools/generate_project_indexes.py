#!/usr/bin/env python3
"""Deterministic on-demand directory inventories for skl-SF.

Source is the Git worktree, not an LLM-generated guess. No source code is parsed
or sent to a model; each folder gets a small, direct FILES.md.
"""
from __future__ import annotations

import argparse
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
OUT = "FILES.md"
SKIP = {OUT, "INDEX.md"}
BANNER = "<!-- Generated by tools/generate_project_indexes.py; do not edit manually. -->"


def list_paths(root: Path) -> list[str]:
    proc = subprocess.run(
        ["git", "-C", str(root), "ls-files", "--cached", "--others", "--exclude-standard", "-z"],
        capture_output=True, check=True
    )
    names = {s.decode("utf-8") for s in proc.stdout.split(b"\0") if s}
    return sorted(
        name for name in names
        if Path(name).name not in SKIP
        and (root / name).is_file()
        and not any(s in (".git", ".godot", "__pycache__") for s in Path(name).parts)
    )


def render(paths: list[str]) -> dict[str, str]:
    by_dir: dict[str, set[str]] = {}
    dirs = {"."}
    for filename in paths:
        parts = filename.split("/")
        folder = "." if len(parts) == 1 else "/".join(parts[:-1])
        by_dir.setdefault(folder, set()).add(parts[-1])
        for i in range(1, len(parts)):
            dirs.add("/".join(parts[:i]))
    results: dict[str, str] = {}
    tick = chr(96)
    for folder in sorted(dirs):
        prefix = "" if folder == "." else folder + "/"
        children = sorted(d[len(prefix):] for d in dirs if d.startswith(prefix)
                          and d != folder and d[len(prefix):] and "/" not in d[len(prefix):])
        title = "./" if folder == "." else folder + "/"
        lines = ["# Files in " + tick + title + tick, "", BANNER, "",
                 "This is a complete direct-file inventory, not a requirement to read every file.",
                 "", "## Subfolders", ""]
        if children:
            lines += ["- [" + tick + c + "/" + tick + "](" + c + "/" + OUT + ")" for c in children]
        else:
            lines.append("- None")
        lines += ["", "## Files", ""]
        files = sorted(by_dir.get(folder, set()))
        if files:
            lines += ["- [" + tick + f + tick + "](" + f + ")" for f in files]
        else:
            lines.append("- None (folder contains subfolders)")
        lines += ["", "Navigate via INDEX.md if present for semantic routing; consult only relevant files.", ""]
        results[prefix + OUT] = "\n".join(lines)
    return results


def main() -> int:
    parser = argparse.ArgumentParser()
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--write", action="store_true", help="regenerate all inventories")
    group.add_argument("--check", action="store_true", help="fail if inventories are stale")
    args = parser.parse_args()
    expected = render(list_paths(ROOT))
    stale = [path for path, data in expected.items()
             if not (ROOT / path).is_file() or (ROOT / path).read_text(encoding="utf-8") != data]
    existing = {p.relative_to(ROOT).as_posix() for p in ROOT.rglob(OUT)
                if ".git" not in p.parts and ".godot" not in p.parts}
    orphaned = sorted(existing - set(expected))
    if args.write:
        for path, data in expected.items():
            target = ROOT / path
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(data, encoding="utf-8", newline="\n")
        for path in orphaned:
            (ROOT / path).unlink()
        print(f"Updated {len(expected)} folder inventories; removed {len(orphaned)} stale inventories.")
        return 0
    if stale or orphaned:
        print("Stale folder indexes. Run: python tools/generate_project_indexes.py --write")
        for path in stale + orphaned:
            print(" -", path)
        return 1
    print(f"All {len(expected)} folder inventories match the current file tree.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
