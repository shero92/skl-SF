#!/usr/bin/env python3
"""Validate agent task/art records and generate compact status dashboards.

No third-party dependencies and no graphic generation. One canonical record
per TASK/ART ID; dashboard files are deterministic read-only projections.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TASK_DIR = Path(".agents/tasks")
ART_DIR = Path(".agents/graphics/requests")
TASK_BOARD = Path(".agents/project/TASKS.md")
ART_BOARD = Path(".agents/graphics/QUEUE.md")
ACTIVE_BOARD = Path(".agents/project/ACTIVE.md")
TASK_STATES = {"todo", "in_progress", "blocked", "review", "done", "cancelled"}
ART_STATES = {"blocked_reference", "requested", "in_progress", "delivered", "reviewed", "integrated", "cancelled"}
ID_RE = re.compile(r"^(TASK|ART)-[0-9]{4}$")
SHA_RE = re.compile(r"^[0-9a-f]{64}$")
BANNER = "<!-- GENERATED by tools/agent_workflow.py; edit the source TASK/ART record instead. -->"


def read_record(file: Path, kind: str) -> dict[str, str]:
    lines = file.read_text(encoding="utf-8").splitlines()
    if len(lines) < 4 or lines[0] != "---":
        raise ValueError(f"{file}: missing --- frontmatter")
    try:
        end = lines.index("---", 1)
    except ValueError as exc:
        raise ValueError(f"{file}: unterminated frontmatter") from exc
    info: dict[str, str] = {}
    for line in lines[1:end]:
        if ":" not in line:
            raise ValueError(f"{file}: invalid field {line!r}")
        name, value = line.split(":", 1)
        name, value = name.strip(), value.strip()
        if not re.fullmatch(r"[a-z_]+", name) or not value or name in info:
            raise ValueError(f"{file}: invalid/empty/duplicate field {name!r}")
        info[name] = value
    required = ({"id", "status", "owner", "branch", "depends_on", "issue", "art_request", "agent", "touches", "test", "done_when"}
                if kind == "TASK" else
                {"id", "status", "owner", "task", "dedupe_key", "existing_asset_ids", "output_paths"})
    if missing := required - info.keys():
        raise ValueError(f"{file}: missing fields {sorted(missing)}")
    ident = info["id"]
    if not ID_RE.fullmatch(ident) or not ident.startswith(kind + "-"):
        raise ValueError(f"{file}: invalid {kind} ID {ident}")
    if not file.name.startswith(ident + "_"):
        raise ValueError(f"{file}: filename must start with {ident}_")
    valid_states = TASK_STATES if kind == "TASK" else ART_STATES
    if info["status"] not in valid_states:
        raise ValueError(f"{file}: invalid status {info['status']}")
    if not any(line.startswith("# ") for line in lines[end + 1:]):
        raise ValueError(f"{file}: body must include a title")
    info["source_file"] = file.as_posix()
    return info


def records(root: Path, path: Path, prefix: str) -> list[dict[str, str]]:
    return [read_record(f, prefix)
            for f in sorted((root / path).glob(prefix + "-*.md"))]


def generated(root: Path) -> dict[Path, str]:
    tasks = records(root, TASK_DIR, "TASK")
    arts = records(root, ART_DIR, "ART")
    task_by_id = {t["id"]: t for t in tasks}
    art_by_id = {a["id"]: a for a in arts}
    if len(task_by_id) != len(tasks) or len(art_by_id) != len(arts):
        raise ValueError("duplicate TASK or ART ID")
    catalog_file = root / "map_factory/metadata/asset_index.json"
    catalog = json.loads(catalog_file.read_text(encoding="utf-8"))
    known_ids = {a["id"] for a in catalog.get("assets", [])}
    requested_outputs: set[str] = set()
    requested_needs: set[str] = set()
    for task in tasks:
        for dep in task["depends_on"].split(","):
            dep = dep.strip()
            if dep != "none" and dep not in task_by_id:
                raise ValueError(f"{task['id']}: unknown dependency {dep}")
            if dep == task["id"]:
                raise ValueError(f"{task['id']}: circular self-dependency")
        a = task["art_request"]
        if a != "none" and a not in art_by_id:
            raise ValueError(f"{task['id']}: unknown art request {a}")
        if task["status"] in {"review", "done"} and task["branch"] == "none":
            raise ValueError(f"{task['id']}: review/done must record branch")
    active = [t for t in tasks if t["status"] == "in_progress"]
    def touch_list(task):
        raw = [p.strip().replace("\\", "/") for p in task["touches"].split(",") if p.strip()]
        if not raw or len(raw) != len(set(raw)):
            raise ValueError(task["id"] + ": touches must list unique explicit paths")
        for path in raw:
            loc = Path(path)
            if loc.is_absolute() or ".." in loc.parts or "*" in path or path.startswith("/"):
                raise ValueError(task["id"] + ": invalid touches " + path)
            if any(part.lower() in ("characters", "ui", "portraits") for part in loc.parts):
                raise ValueError(task["id"] + ": characters/gameplay/UI out of scope")
        return raw
    def collide(a, b):
        return a == b or a.rstrip("/") + "/" == b[:len(a.rstrip("/"))+1] or b.rstrip("/") + "/" == a[:len(b.rstrip("/"))+1]
    for task in tasks:
        if task["agent"] not in {"claude", "codex", "graphics"}:
            raise ValueError(task["id"] + ": agent must be claude|codex|graphics")
        if task["test"] in ("none", "") or task["done_when"] in ("none", ""):
            raise ValueError(task["id"] + ": missing test/done_when")
        touch_list(task)
    for i, a in enumerate(active):
        if a["agent"] in ("claude", "codex") and any(
                b["agent"] == a["agent"] for b in active[i+1:]):
            raise ValueError("Agent has more than one active task: " + a["agent"])
        for other in active[i+1:]:
            if any(collide(x,y) for x in touch_list(a) for y in touch_list(other)):
                raise ValueError("Parallel tasks have overlapping touches: " + a["id"] + " " + other["id"])
    active_lines = ["# Active agent tasks", "", BANNER, "",
                    "Generated only on main after claims/merges. Unknown cost is not zero.", "",
                    "| Agent | Task | Touches | Started | Status | USD so far |",
                    "| --- | --- | --- | --- | --- | --- |"]
    for t in active:
        active_lines.append("| " + t["agent"] + " | " + t["id"] + " | "
                            + t["touches"].replace(",", ", ") + " | "
                            + t.get("started_at", "unknown") + " | in_progress | "
                            + t.get("cost_usd", "unknown") + " |")
    if not active:
        active_lines.append("| — | none | — | — | — | — |")
    out[ACTIVE_BOARD] = "\n".join(active_lines) + "\n"
    for art in arts:
        rid = art["id"]
        need = art["dedupe_key"]
        if not re.fullmatch(r"[a-z0-9][a-z0-9_]{4,80}", need):
            raise ValueError(f"{rid}: dedupe_key must be a stable snake_case need")
        if need in requested_needs:
            raise ValueError(f"{rid}: duplicated art requirement dedupe_key: {need}")
        requested_needs.add(need)
        if art["task"] not in task_by_id:
            raise ValueError(f"{rid}: task {art['task']} does not exist")
        ids = [x.strip() for x in art["existing_asset_ids"].split(",") if x.strip()]
        for asset in ids:
            if asset != "none" and asset not in known_ids:
                raise ValueError(f"{rid}: existing catalog ID not found: {asset}")
        raw_paths = [p.strip() for p in art["output_paths"].split(",") if p.strip()]
        if not raw_paths:
            raise ValueError(f"{rid}: output_paths empty")
        for output in raw_paths:
            pp = Path(output)
            if (pp.is_absolute() or ".." in pp.parts or
                    not output.startswith(f".agents/graphics/deliveries/{rid}/") or
                    pp.suffix.lower() != ".png"):
                raise ValueError(f"{rid}: invalid output location {output}")
            if output in requested_outputs:
                raise ValueError(f"{rid}: output path requested more than once: {output}")
            requested_outputs.add(output)
        if art["status"] in {"delivered", "reviewed", "integrated"}:
            manifest_file = root / f".agents/graphics/deliveries/{rid}/manifest.json"
            if not manifest_file.is_file():
                raise ValueError(f"{rid}: missing delivery manifest")
            manifest = json.loads(manifest_file.read_text(encoding="utf-8"))
            if manifest.get("request_id") != rid:
                raise ValueError(f"{rid}: delivery manifest request_id mismatch")
            items = manifest.get("files", [])
            if sorted(x["path"] for x in items) != sorted(raw_paths):
                raise ValueError(f"{rid}: delivery manifest PNG paths mismatch")
            for item in items:
                sha = item.get("sha256", "")
                file = root / item["path"]
                if not SHA_RE.fullmatch(sha) or not file.is_file():
                    raise ValueError(f"{rid}: missing file/hash for {item['path']}")
                if hashlib.sha256(file.read_bytes()).hexdigest() != sha:
                    raise ValueError(f"{rid}: delivery SHA-256 mismatch: {item['path']}")
    out = {}
    lines = ["# Current task queue", "", BANNER, "",
             "State is authoritative in each linked TASK file; actual code changes are proven by Git PRs.",
             "Read only the task you need. Full guide: [tasks workflow](../workflows/TASKS.md).",
             "", "| Task | State | Owner | Dependencies | Art |", "| --- | --- | --- | --- | --- |"]
    for task in tasks:
        filename = Path(task["source_file"]).name
        lines.append(f"| [{task['id']}](../tasks/{filename}) | {task['status']} | {task['owner']} | {task['depends_on']} | {task['art_request']} |")
    if not tasks:
        lines.append("| — | no tasks | — | — | — |")
    out[TASK_BOARD] = "\n".join(lines) + "\n"
    lines = ["# Graphics production queue", "", BANNER, "",
             "Only graphics specialists create PNGs. A request is not a delivered image.",
             "Read only the linked ART request. Guide: [graphics workflow](../workflows/GRAPHICS.md).",
             "", "| Request | State | Specialist | Related task | Existing IDs |", "| --- | --- | --- | --- | --- |"]
    for art in arts:
        filename = Path(art["source_file"]).name
        lines.append(f"| [{art['id']}](requests/{filename}) | {art['status']} | {art['owner']} | {art['task']} | {art['existing_asset_ids']} |")
    if not arts:
        lines.append("| — | no graphics requests | — | — | — |")
    out[ART_BOARD] = "\n".join(lines) + "\n"
    return out


def main() -> int:
    parser = argparse.ArgumentParser()
    modes = parser.add_mutually_exclusive_group(required=True)
    modes.add_argument("--write", action="store_true")
    modes.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        generated_files = generated(ROOT)
    except (ValueError, KeyError, OSError, json.JSONDecodeError) as exc:
        print(f"Invalid agent tracking data: {exc}", file=sys.stderr)
        return 1
    stale = [p for p, value in generated_files.items()
             if not (ROOT / p).exists() or (ROOT / p).read_text(encoding="utf-8") != value]
    if args.write:
        for p, value in generated_files.items():
            dest = ROOT / p
            dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_text(value, encoding="utf-8")
        print(f"Updated {len(generated_files)} generated task/art boards")
        return 0
    if stale:
        print("Stale queues: " + ", ".join(str(s) for s in stale), file=sys.stderr)
        print("Run: python tools/agent_workflow.py --write", file=sys.stderr)
        return 1
    print("Task/art records, deduplication and generated queues validated.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
