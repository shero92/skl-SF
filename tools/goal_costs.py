#!/usr/bin/env python3
"""Reproducible per-goal cost rollup from committed receipts only."""
import argparse
import json
from pathlib import Path
import re
import sys

sys.path.insert(0,str(Path(__file__).resolve().parent))
from runner_safety import receipt_goals
ROOT=Path(__file__).resolve().parents[1]
BASE=ROOT/".agents/monitoring"

def build(root=ROOT):
    mapping={}
    goals_file=root/".agents/planner/goals.json"
    if goals_file.exists():
        for goal in json.loads(goals_file.read_text(encoding="utf-8")).get("goals",[]):
            for task in goal.get("task_ids",[]):mapping[task]=goal["id"]
    for f in sorted((root/".agents/tasks").glob("TASK-*.md")):
        text=f.read_text(encoding="utf-8")
        match=re.search(r"(?m)^id: (TASK-\d{4})$",text)
        goal=re.search(r"(?m)^\*\*Goal:\*\* (GOAL-\d{4})$",text)
        source=re.search(r"(?m)^\*\*Source:\*\* goal:(GOAL-\d{4}):",text)
        if match and (goal or source):
            mapping[match.group(1)]=(goal or source).group(1)
    receipts=[]
    for f in sorted((root/".agents/monitoring/receipts").glob("TASK-*.json")):
        receipts.append(json.loads(f.read_text(encoding="utf-8")))
    result=receipt_goals(receipts,mapping)
    lines=["# Cost by long-term goal","","<!-- GENERATED by tools/goal_costs.py -->","",
        "| Goal | Known API-equivalent USD | Unknown cost receipts | Input tokens | Output tokens | Receipts |",
        "| --- | ---: | ---: | ---: | ---: | ---: |"]
    for row in result:
        lines.append("| {goal} | {known_usd:.6f} | {unknown_cost_receipts} | {input_tokens} | {output_tokens} | {receipts} |".format(**row))
    lines+=["","These are API-equivalent estimates, NOT subscription charges. Unknown costs remain unknown.",""]
    return {".agents/monitoring/goal_summary.json":json.dumps({"goals":result},indent=2)+"\n",
            ".agents/monitoring/goal_summary.md":"\n".join(lines)}

def main():
    p=argparse.ArgumentParser()
    x=p.add_mutually_exclusive_group(required=True)
    x.add_argument("--write",action="store_true")
    x.add_argument("--check",action="store_true")
    args=p.parse_args()
    missing=[]
    for rel,body in build().items():
        path=ROOT/rel
        if args.write:
            path.parent.mkdir(parents=True,exist_ok=True)
            path.write_text(body,encoding="utf-8")
        elif not path.is_file() or path.read_text(encoding="utf-8")!=body:
            missing.append(rel)
    if missing:
        print("Stale goal reports: "+", ".join(missing),file=sys.stderr)
        return 1
    return 0

if __name__=="__main__":
    sys.exit(main())
