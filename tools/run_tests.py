#!/usr/bin/env python3
"""Test router: run the tests that cover what changed.

tools/test_map.json maps path globs to test commands. Any changed path that no
test claims runs ALL tests (fail safe). Only commands from the map are executed.

  py -3 tools/run_tests.py --changed        # vs origin/main, incl. uncommitted
  py -3 tools/run_tests.py --all
  py -3 tools/run_tests.py --list
  py -3 tools/run_tests.py --changed --dry-run
"""
from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys
import time

ROOT = Path(__file__).resolve().parents[1]
MAP = ROOT / "tools/test_map.json"
INDEX = ROOT / "tools/tests/INDEX.md"
CONFIG = ROOT / ".agents/planner/config.json"
KINDS = ("python", "godot")
BANNER = "<!-- Generated by tools/run_tests.py --write-index from tools/test_map.json; do not edit manually. -->"


def load_map(path: Path = MAP) -> list[dict]:
    data = json.loads(path.read_text(encoding="utf-8"))
    tests = data["tests"]
    seen = set()
    for t in tests:
        missing = {"id", "kind", "covers", "command", "paths"} - set(t)
        if missing:
            raise ValueError(f"test {t.get('id', '?')} missing {sorted(missing)}")
        if t["id"] in seen:
            raise ValueError("duplicate test id " + t["id"])
        if t["kind"] not in KINDS:
            raise ValueError(f"test {t['id']} has unknown kind {t['kind']}")
        if not t["command"] or not t["paths"]:
            raise ValueError(f"test {t['id']} needs a command and at least one path")
        seen.add(t["id"])
    return tests


def glob_regex(pattern: str) -> re.Pattern:
    out, i = "", 0
    while i < len(pattern):
        if pattern.startswith("**/", i):
            out, i = out + "(?:.*/)?", i + 3
        elif pattern.startswith("**", i):
            out, i = out + ".*", i + 2
        elif pattern[i] == "*":
            out, i = out + "[^/]*", i + 1
        elif pattern[i] == "?":
            out, i = out + "[^/]", i + 1
        else:
            out, i = out + re.escape(pattern[i]), i + 1
    return re.compile(out + r"\Z")


def matches(path: str, globs: list[str]) -> bool:
    path = path.replace("\\", "/")
    return any(glob_regex(g).match(path) for g in globs)


def select(tests: list[dict], changed: list[str]) -> tuple[list[dict], list[str]]:
    """Return (tests to run, changed paths no test claims). Unclaimed paths run everything."""
    unmatched = [p for p in changed if not any(matches(p, t["paths"]) for t in tests)]
    if unmatched:
        return list(tests), unmatched
    return [t for t in tests if any(matches(p, t["paths"]) for p in changed)], []


def _git(*args: str, cwd: Path) -> list[str]:
    proc = subprocess.run(["git", *args], cwd=str(cwd), capture_output=True, text=True,
                          encoding="utf-8", errors="replace")
    if proc.returncode:
        raise RuntimeError("git " + " ".join(args) + ": " + proc.stderr.strip())
    return [line for line in proc.stdout.splitlines() if line]


def changed_paths(base: str = "origin/main", cwd: Path = ROOT) -> list[str]:
    """Committed changes since the merge-base with base, plus staged, unstaged and untracked."""
    found = set(_git("diff", "--name-only", "--no-renames", base + "...HEAD", cwd=cwd))
    found |= set(_git("diff", "--name-only", "--no-renames", "HEAD", cwd=cwd))
    found |= set(_git("ls-files", "--others", "--exclude-standard", cwd=cwd))
    return sorted(found)


def godot_executable(override: str | None = None) -> str:
    if override:
        return override
    if os.environ.get("GODOT_EXECUTABLE"):
        return os.environ["GODOT_EXECUTABLE"]
    if CONFIG.is_file():
        configured = json.loads(CONFIG.read_text(encoding="utf-8")).get("godot_executable")
        if configured:
            return configured
    return "godot"


def resolve(test: dict, godot: str) -> list[str]:
    swap = {"{python}": sys.executable, "{godot}": godot}
    return [swap[part] if part in swap else str(part) for part in test["command"]]


def display(test: dict) -> str:
    swap = {"{python}": "python", "{godot}": "<godot>"}
    return " ".join(swap[part] if part in swap else str(part) for part in test["command"])


def render_index(tests: list[dict]) -> str:
    tick = chr(96)
    lines = ["# Tests", "", BANNER, "",
             "Run the tests for what you changed with " + tick + "py -3 tools/run_tests.py --changed" + tick
             + " (vs origin/main, including uncommitted files). A changed path that no test claims runs ALL tests.",
             "Use " + tick + "--all" + tick + ", " + tick + "--only ID" + tick + ", " + tick + "--kind python|godot" + tick
             + ", " + tick + "--list" + tick + " or " + tick + "--dry-run" + tick + ". "
             + tick + "<godot>" + tick + " is " + tick + "godot_executable" + tick + " in "
             + tick + ".agents/planner/config.json" + tick + " (override: " + tick + "--godot" + tick
             + " or " + tick + "GODOT_EXECUTABLE" + tick + ").",
             "Passing tests do not certify artistic similarity. [Full file listing](FILES.md).", "",
             "| Test | Kind | Covers | Command |", "| --- | --- | --- | --- |"]
    for t in tests:
        lines.append(f"| {tick}{t['id']}{tick} | {t['kind']} | {t['covers']} | {tick}{display(t)}{tick} |")
    lines += ["", "## Paths per test", ""]
    for t in tests:
        lines.append(f"- {tick}{t['id']}{tick}: " + ", ".join(tick + p + tick for p in t["paths"]))
    return "\n".join(lines) + "\n"


def tree_state(cwd: Path = ROOT) -> tuple[set[str], set[str]]:
    """(tracked paths differing from HEAD, untracked paths)."""
    return (set(_git("diff", "--name-only", "--no-renames", "HEAD", cwd=cwd)),
            set(_git("ls-files", "--others", "--exclude-standard", cwd=cwd)))


def undo_side_effects(before: tuple[set[str], set[str]], cwd: Path = ROOT) -> list[str]:
    """Revert files a test dirtied that were clean before it ran (Godot's editor rewrites
    scripts from its saved session and adds .import files). Pre-existing edits are untouched."""
    modified, untracked = tree_state(cwd)
    touched = sorted(modified - before[0])
    created = sorted(untracked - before[1])
    if touched:
        _git("checkout", "HEAD", "--", *touched, cwd=cwd)
    for path in created:
        (cwd / path).unlink(missing_ok=True)
    return touched + created


def tail(text: str, count: int = 25) -> str:
    return "\n".join(text.strip().splitlines()[-count:])


def run(tests: list[dict], godot: str, timeout: int) -> int:
    failures = []
    for t in tests:
        argv = resolve(t, godot)
        start = time.monotonic()
        if t["kind"] == "godot" and not (Path(godot).is_file() or shutil.which(godot)):
            failures.append(t["id"])
            print(f"FAIL {t['id']}: godot executable not found: {godot}")
            continue
        before = tree_state() if t["kind"] == "godot" else None
        try:
            proc = subprocess.run(argv, cwd=str(ROOT), capture_output=True, text=True,
                                  encoding="utf-8", errors="replace", timeout=timeout)
            code, output = proc.returncode, proc.stdout + proc.stderr
        except subprocess.TimeoutExpired:
            code, output = "timeout", f"timed out after {timeout}s"
        except OSError as exc:
            code, output = "error", str(exc)
        seconds = time.monotonic() - start
        if before is not None:
            reverted = undo_side_effects(before)
            if reverted:
                print(f"NOTE {t['id']} changed {len(reverted)} file(s); reverted: " + ", ".join(reverted))
        if code == 0:
            print(f"PASS {t['id']} ({seconds:.1f}s)")
        else:
            failures.append(t["id"])
            print(f"FAIL {t['id']} ({seconds:.1f}s, exit {code})")
            print("  " + tail(output).replace("\n", "\n  "))
    print(f"\n{len(tests) - len(failures)}/{len(tests)} passed" + (": failed " + ", ".join(failures) if failures else ""))
    return 1 if failures else 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Run the tests that cover changed paths.")
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--changed", action="store_true", help="tests for paths changed vs --base, incl. uncommitted")
    mode.add_argument("--all", action="store_true", help="run every test")
    mode.add_argument("--only", action="append", metavar="ID", help="run one test by id (repeatable)")
    mode.add_argument("--list", action="store_true", help="list tests and exit")
    mode.add_argument("--write-index", action="store_true", help="regenerate tools/tests/INDEX.md")
    mode.add_argument("--check-index", action="store_true", help="fail if tools/tests/INDEX.md is stale")
    parser.add_argument("--dry-run", action="store_true", help="print selected commands without running them")
    parser.add_argument("--base", default="origin/main", help="git ref to diff against (default origin/main)")
    parser.add_argument("--kind", choices=KINDS, help="only run tests of this kind")
    parser.add_argument("--godot", help="Godot executable (default: GODOT_EXECUTABLE or planner config)")
    parser.add_argument("--timeout", type=int, default=600, help="seconds per test (default 600)")
    parser.add_argument("--map", type=Path, default=MAP, help=argparse.SUPPRESS)
    args = parser.parse_args(argv)

    try:
        tests = load_map(args.map)
    except (OSError, ValueError, KeyError) as exc:
        print("Invalid test map:", exc)
        return 2

    if args.write_index or args.check_index:
        expected = render_index(tests)
        if args.write_index:
            INDEX.write_text(expected, encoding="utf-8")
            print("Wrote", INDEX.relative_to(ROOT).as_posix())
            return 0
        if not INDEX.is_file() or INDEX.read_text(encoding="utf-8") != expected:
            print("tools/tests/INDEX.md is stale. Run: py -3 tools/run_tests.py --write-index")
            return 1
        print("tools/tests/INDEX.md matches tools/test_map.json")
        return 0

    if args.list:
        for t in tests:
            print(f"{t['id']:<24} {t['kind']:<7} {t['covers']}")
        return 0

    if args.changed:
        try:
            changed = changed_paths(args.base)
        except RuntimeError as exc:
            print("Cannot diff against", args.base, "-", exc, "\nRunning ALL tests.")
            changed, selected, unmatched = None, list(tests), []
        else:
            selected, unmatched = select(tests, changed)
            print(f"{len(changed)} changed path(s) vs {args.base}")
            if unmatched:
                print("Not covered by tools/test_map.json, running ALL tests:")
                for path in unmatched[:20]:
                    print("  " + path)
                if len(unmatched) > 20:
                    print(f"  ... and {len(unmatched) - 20} more")
    elif args.only:
        unknown = set(args.only) - {t["id"] for t in tests}
        if unknown:
            print("Unknown test id(s):", ", ".join(sorted(unknown)))
            return 2
        selected = [t for t in tests if t["id"] in args.only]
    else:
        selected = list(tests)

    if args.kind:
        selected = [t for t in selected if t["kind"] == args.kind]
    if not selected:
        print("No tests selected.")
        return 0
    godot = godot_executable(args.godot)
    if args.dry_run:
        for t in selected:
            print(f"{t['id']}: " + subprocess.list2cmdline(resolve(t, godot)))
        print(f"\n{len(selected)} test(s) selected (dry run)")
        return 0
    return run(selected, godot, args.timeout)


if __name__ == "__main__":
    sys.exit(main())
