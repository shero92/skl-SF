"""Sort the owner HD masters into sub folders and write catalogs (local helper).

Usage: python tools/organize_hd_masters.py [--apply]

Without --apply it only prints the plan. With --apply it moves every master from
`assets_hd/<category>/<name>_NN.png` to `assets_hd/<category>/<name>/<name>_NN.png` (the sub folder
is the file stem without its trailing number), moves the matching `.import` file, rewrites the paths
in `assets_hd/manifest.json` and the `master` paths in `assets_hd/hd_map.json`, verifies sha256 of
every moved file against the manifest (nothing is edited, resized or deleted) and writes
`assets_hd/CATALOG.md` plus a `CATALOG.md` in every category folder.

Execution provenance: Agent: claude (Claude Code); model: Sonnet 5.5.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import re
import shutil

ROOT = Path(__file__).resolve().parents[1]
HD = ROOT / "assets_hd"
NUMBER = re.compile(r"_\d+$")


def subfolder(path: str) -> str:
    return NUMBER.sub("", Path(path).stem)


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def plan(items: list[dict]) -> list[tuple[str, str]]:
    """(old relative path, new relative path) under assets_hd for every master."""
    moves = []
    for item in items:
        old = Path(item["path"]).relative_to("assets_hd")
        category = old.parts[0]
        if len(old.parts) == 3:  # already sorted
            moves.append((old.as_posix(), old.as_posix()))
            continue
        moves.append((old.as_posix(), (Path(category) / subfolder(old.name) / old.name).as_posix()))
    return moves


def write_catalogs(items: list[dict], used: set[str]) -> None:
    by_category: dict[str, list[dict]] = {}
    for item in items:
        by_category.setdefault(item["category"], []).append(item)
    lines = ["# HD masters catalog", "",
             "Generated by tools/organize_hd_masters.py. Masters are owner supplied, kept local (not in git) and never edited.",
             "Layout: `assets_hd/<category>/<group>/<group>_NN.png`. `runtime` = a 2x runtime texture is built from it.", "",
             f"Total masters: {len(items)}", "", "| Category | Groups | Masters |", "| --- | ---: | ---: |"]
    for category in sorted(by_category):
        groups = {subfolder(i["path"]) for i in by_category[category]}
        lines.append(f"| [{category}]({category}/) | {len(groups)} | {len(by_category[category])} |")
    (HD / "CATALOG.md").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    for category, rows in by_category.items():
        text = [f"# {category} masters", "", "| Group | File | Size | Runtime | sha256 (first 12) |", "| --- | --- | --- | --- | --- |"]
        for item in sorted(rows, key=lambda r: r["path"]):
            group = subfolder(item["path"])
            flag = "yes" if item["path"].removeprefix("assets_hd/") in used else ""
            text.append(f"| {group} | {Path(item['path']).name} | {item['size'][0]}x{item['size'][1]} | {flag} | {item['sha256'][:12]} |")
        (HD / category / "CATALOG.md").write_text("\n".join(text) + "\n", encoding="utf-8", newline="\n")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--apply", action="store_true")
    args = parser.parse_args()
    manifest = json.loads((HD / "manifest.json").read_text(encoding="utf-8"))
    items = manifest["items"]
    moves = plan(items)
    groups = {Path(new).parent.as_posix() for _old, new in moves}
    print(f"{len(items)} masters, {len(groups)} groups")
    if not args.apply:
        for old, new in moves[:8]:
            print(f"  {old} -> {new}")
        return 0
    remap = {}
    for item, (old, new) in zip(items, moves):
        source, target = HD / old, HD / new
        if old != new:
            target.parent.mkdir(parents=True, exist_ok=True)
            if not source.exists():
                raise SystemExit(f"missing master: {old}")
            shutil.move(str(source), str(target))
            imported = Path(str(source) + ".import")
            if imported.exists():
                shutil.move(str(imported), str(target) + ".import")
        if digest(target) != item["sha256"]:
            raise SystemExit(f"sha256 mismatch after move: {new}")
        remap[old] = new
        item["path"] = "assets_hd/" + new
    (HD / "manifest.json").write_text(json.dumps(manifest, indent=1) + "\n", encoding="utf-8", newline="\n")
    hd_map_path = HD / "hd_map.json"
    hd_map = json.loads(hd_map_path.read_text(encoding="utf-8"))
    for record in hd_map["map"].values():
        record["master"] = remap.get(record["master"], record["master"])
        if not (HD / record["master"]).exists():
            raise SystemExit("hd_map master missing: " + record["master"])
    hd_map_path.write_text(json.dumps(hd_map, indent=1) + "\n", encoding="utf-8", newline="\n")
    used = {r["master"] for r in hd_map["map"].values()}
    write_catalogs(items, used)
    print("done; sha256 verified for every master")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
